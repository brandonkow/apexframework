import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "C:/Users/user/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
const out = process.env.JOURNEY_CHECK_OUTPUT || "C:/Users/user/OneDrive/Documents/New project/outputs/apex-journey";
const base = process.env.JOURNEY_CHECK_URL || "http://127.0.0.1:3210";
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: "chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(base + "/#journey", { waitUntil: "networkidle", timeout: 60000 });
  await page.waitForSelector('body[data-ready="true"]', { timeout: 40000 });
  await page.waitForSelector("#worldWrap.world-ready", { timeout: 40000 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await page.locator("#worldWrap").getAttribute("data-meshes"), "63");
  await page.screenshot({ path: path.join(out, "desktop.png"), fullPage: true });
  console.log("desktop", await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, ready: document.querySelector("#worldWrap").classList.contains("world-ready"), meshes: document.querySelector("#worldWrap").dataset.meshes, width: innerWidth })));
  await page.locator('[data-level="3"]').click({ force: true });
  console.log("lock notice", await page.locator("#notice").innerText());
  assert.match(await page.locator("#notice").innerText(), /Clear the earlier levels/);
  await page.locator("#motionToggle").click();
  assert.equal(await page.locator("#motionToggle").getAttribute("aria-pressed"), "true");
  await page.waitForTimeout(300);
  const before = await page.locator("#worldCanvas").screenshot();
  await page.locator("#worldCanvas").press("ArrowLeft");
  await page.waitForTimeout(300);
  assert.notDeepEqual(await page.locator("#worldCanvas").screenshot(), before, "Keyboard rotates the real 3D view");
  await page.locator("#resetView").click();
  await page.locator('[data-action="enter"]').click();
  await page.locator('[data-field="projectName"]').fill("Browser Test Residence");
  await page.locator('[data-field="area"]').fill("Bayan Lepas");
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForSelector('body[data-ready="true"]');
  await page.locator('[data-checkpoint="0"]').click();
  console.log("persistence", await page.locator('[data-field="projectName"]').inputValue());
  assert.equal(await page.locator('[data-field="projectName"]').inputValue(), "Browser Test Residence");
  await page.screenshot({ path: path.join(out, "desktop-checkpoint.png"), fullPage: true });
  await page.locator("#newCandidate").click();
  await page.waitForTimeout(500);
  console.log("candidate isolation", await page.locator("#candidateSelect option").count());
  assert.equal(await page.locator("#candidateSelect option").count(), 2);
  await page.locator('[data-area="desk"]').click();
  await page.waitForSelector('#workbench[data-ready="true"]');
  await page.locator('[data-area="journey"]').click();
  await page.waitForSelector('#worldWrap.world-ready');
  assert.ok(await page.locator('#worldCanvas').evaluate(node => node.width > 0 && node.height > 0));
  await page.close();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
  mobile.on("pageerror", error => { errors.push(error.message); console.log("mobile error", error.message); });
  await mobile.goto(base + "/#journey", { waitUntil: "networkidle" });
  await mobile.waitForSelector('body[data-ready="true"]', { timeout: 60000 });
  await mobile.screenshot({ path: path.join(out, "mobile.png"), fullPage: true });
  await mobile.locator('[data-action="enter"]').click();
  await mobile.screenshot({ path: path.join(out, "mobile-checkpoint.png"), fullPage: true });
  console.log("mobile", await mobile.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, width: innerWidth, canvas: document.querySelector("#worldCanvas").clientWidth })));
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await mobile.locator("#motionToggle").getAttribute("aria-pressed"), "true");
  assert.equal(await mobile.locator('[data-area="desk"]').isVisible(), true);
  await mobile.locator("#mapToggle").tap();
  assert.equal(await mobile.locator("body").evaluate(node => node.classList.contains("flat-view")), true);
  await mobile.locator("#mapToggle").tap();
  assert.equal(await mobile.locator("body").evaluate(node => node.classList.contains("flat-view")), false);
  console.log("page errors", errors);
  if (errors.length) process.exitCode = 1;
} finally { await browser.close(); }
